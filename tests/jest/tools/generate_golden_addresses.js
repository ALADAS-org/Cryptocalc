/**
 * ============================================================================
 * Generator of the golden addresses (tests/jest/fixtures/expected/golden_addresses.json)
 * ============================================================================
 * Captures, from the CURRENT code, the values of every golden case
 * (see tests/jest/unit/wallet/helpers/golden_wallets.js).
 *
 * Usage (from the project root, Windows or Linux):
 *     node tests/jest/tools/generate_golden_addresses.js           -> compare only, exit code 1 if different
 *     node tests/jest/tools/generate_golden_addresses.js --write   -> (re)write the file
 *
 * Only run '--write' on purpose: the golden addresses are the safety net of the
 * refactorings. A lot which changes addresses on purpose (lot 6) regenerates the
 * file, and the git diff of the file lists every changed value.
 *
 * WARNING: the file contains the private keys of PUBLIC test vectors.
 *          NEVER send funds to these addresses.
 * ============================================================================
 */
'use strict';
const fs   = require('fs');
const path = require('path');

const { PrettyLog, UNIT_TESTS_LOG_MODE } = require('../../../www/js/util/log/log_utils.js');
const { GOLDEN_CASES, computeGoldenEntry } = require('../unit/wallet/helpers/golden_wallets.js');

const GOLDEN_PATH  = path.join(__dirname, '../fixtures/expected/golden_addresses.json');
const WRITE_OPTION = '--write';
const WARNING      = 'Private keys of PUBLIC test vectors: NEVER send funds to these addresses. '
                   + 'Generated by tests/jest/tools/generate_golden_addresses.js --write';

const silenced = async (task) => {
  const saved = { log: console.log, warn: console.warn, info: console.info };
  console.log = console.warn = console.info = () => {};
  try { return await task(); }
  finally { Object.assign(console, saved); }
};

const computeGoldenFile = async () => {
  PrettyLog.This.logMode = UNIT_TESTS_LOG_MODE;
  const entries = {};
  for (const golden_case of GOLDEN_CASES) {
    entries[golden_case.key] = await silenced(() => computeGoldenEntry(golden_case));
    process.stdout.write('.');
  }
  process.stdout.write('\n');
  return { _warning: WARNING, entries };
};

const main = async () => {
  const content = JSON.stringify(await computeGoldenFile(), null, 2) + '\n';
  if (process.argv.includes(WRITE_OPTION)) {
    fs.writeFileSync(GOLDEN_PATH, content, 'utf8');
    console.log('Written: ' + GOLDEN_PATH + ' (' + GOLDEN_CASES.length + ' entries)');
    return 0;
  }
  const current = fs.existsSync(GOLDEN_PATH) ? fs.readFileSync(GOLDEN_PATH, 'utf8').replace(/\r\n/g, '\n') : '';
  const same = (current === content);
  console.log(same ? 'Golden addresses unchanged (' + GOLDEN_CASES.length + ' entries)'
                   : 'Golden addresses DIFFER from ' + GOLDEN_PATH + ' (use ' + WRITE_OPTION + ' to rewrite)');
  return same ? 0 : 1;
};

main().then((code) => process.exit(code), (error) => { console.error(error); process.exit(2); });
